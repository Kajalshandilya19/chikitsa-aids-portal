import path from 'node:path';
import ExcelJS from 'exceljs';
import { SOCH_COLUMNS } from '../imports/soch-columns';

/**
 * `npm run fixture:soch` writes fixtures/soch-sample.xlsx: SYNTHETIC SOCH rows for building and testing
 * the Phase 1 import (docs/SEED_DATA.md §4). Deterministic (fixed seed), so the file only changes when
 * this script or SOCH_COLUMNS changes.
 *
 * Safety: no row contains a VALID Aadhaar, mobile or ABHA number. A random checksum-valid Aadhaar could
 * belong to a real person, and this file is about HIV. Those columns are blank, or deliberately invalid
 * in the error rows. Names are random pairs from common-name lists.
 *
 * Rows: 500 valid rows across the placeholder Centers RJ001..RJ041, then 8 deliberate error rows
 * (the last rows of the sheet) that the importer must reject:
 *   bad date, future date, unknown facility, duplicate UID, invalid Aadhaar, missing name, bad sex, bad age.
 */
let seed = 20261002;
const rnd = () => {
  seed = (seed * 1103515245 + 12345) % 2147483648;
  return seed / 2147483648;
};
const pick = <T>(xs: readonly T[]): T => xs[Math.floor(rnd() * xs.length)] as T;
const pad = (n: number, w: number) => String(n).padStart(w, '0');

const FIRST_F = ['Asha', 'Sunita', 'Kamla', 'Geeta', 'Pooja', 'Rekha', 'Meena', 'Santosh', 'Laxmi', 'Radha', 'Kavita', 'Sarita'];
const FIRST_M = ['Ramesh', 'Suresh', 'Mahesh', 'Rajesh', 'Mukesh', 'Prakash', 'Dinesh', 'Gopal', 'Mohan', 'Shankar', 'Bhanwar', 'Hari'];
const LAST = ['Sharma', 'Meena', 'Jat', 'Gurjar', 'Rawat', 'Saini', 'Kumawat', 'Bairwa', 'Choudhary', 'Yadav', 'Singh', 'Devi'];
const STATUS = ['On ART', 'On ART', 'On ART', 'On ART', 'MIS', 'LFU', 'Transferred Out', 'Died', 'Opted Out'];
const TEHSIL = ['Kishangarh', 'Beawar', 'Nasirabad', 'Kekri', 'Sarwar', 'Masuda'];

const date = (fromYear: number, toYear: number) => {
  const y = fromYear + Math.floor(rnd() * (toYear - fromYear + 1));
  return `${pad(1 + Math.floor(rnd() * 28), 2)}-${pad(1 + Math.floor(rnd() * 12), 2)}-${y}`;
};

const main = async () => {
  const rows: Record<string, string>[] = [];
  for (let i = 1; i <= 500; i++) {
    const center = `RJ${pad(1 + Math.floor(rnd() * 41), 3)}`;
    const female = rnd() < 0.45;
    const tg = rnd() < 0.03;
    const regYear = 2008 + Math.floor(rnd() * 17);
    rows.push({
      soch_beneficiary_id: `B${pad(i, 7)}`,
      soch_uid: `RJUID${pad(i, 7)}`,
      art_registration_date: date(regYear, regYear),
      pre_art_number: `PREART/${center}/${pad(i, 4)}`,
      art_number: `ART/${center}/${regYear}/${pad(i, 4)}`,
      pid_number: `PID${pad(i, 20)}`,
      patient_name: `${pick(female ? FIRST_F : FIRST_M)} ${pick(LAST)}`,
      address: `House ${1 + Math.floor(rnd() * 400)}, Ward ${1 + Math.floor(rnd() * 30)}`,
      tehsil: pick(TEHSIL),
      district_name: '',
      state_name: 'Rajasthan',
      contact_number: '',
      aadhaar: '',
      age: String(18 + Math.floor(rnd() * 60)),
      sex: tg ? 'TG' : female ? 'F' : 'M',
      art_status: pick(STATUS),
      last_visit_date: date(2024, 2025),
      facility_name: `ART Centre ${center}`,
      facility_code: center,
      abha_number: '',
    });
  }
  const base = rows[0] as Record<string, string>;
  const errors: Record<string, string>[] = [
    { ...base, soch_beneficiary_id: 'E0000001', soch_uid: 'RJUIDE000001', art_registration_date: '31-02-2015' },
    { ...base, soch_beneficiary_id: 'E0000002', soch_uid: 'RJUIDE000002', last_visit_date: '01-01-2999' },
    { ...base, soch_beneficiary_id: 'E0000003', soch_uid: 'RJUIDE000003', facility_code: 'ZZ999' },
    { ...base, soch_beneficiary_id: 'E0000004' },
    { ...base, soch_beneficiary_id: 'E0000005', soch_uid: 'RJUIDE000005', aadhaar: '234123412345' },
    { ...base, soch_beneficiary_id: 'E0000006', soch_uid: 'RJUIDE000006', patient_name: '' },
    { ...base, soch_beneficiary_id: 'E0000007', soch_uid: 'RJUIDE000007', sex: 'X' },
    { ...base, soch_beneficiary_id: 'E0000008', soch_uid: 'RJUIDE000008', age: '150' },
  ];

  const wb = new ExcelJS.Workbook();
  wb.creator = 'Pension Portal fixture generator';
  const ws = wb.addWorksheet('SOCH Export');
  ws.addRow(SOCH_COLUMNS.map((c) => c.header));
  ws.getRow(1).font = { bold: true };
  for (const r of [...rows, ...errors]) ws.addRow(SOCH_COLUMNS.map((c) => r[c.field] ?? ''));
  ws.columns.forEach((c) => {
    c.width = 22;
  });
  const about = wb.addWorksheet('About');
  about.addRow(['SYNTHETIC TEST DATA. These are not real people. Generated by pension-data-service src/dev/make-soch-fixture.ts.']);
  about.addRow(['Rows 2-501 are valid. Rows 502-509 are deliberate errors: bad date, future date, unknown facility, duplicate UID, invalid Aadhaar, missing name, bad sex, bad age.']);
  const out = path.resolve(__dirname, '../../../../fixtures/soch-sample.xlsx');
  await wb.xlsx.writeFile(out);
  console.log(`wrote ${out}: ${rows.length} valid + ${errors.length} error rows`);
};

main().catch((err) => {
  console.error(err);
  process.exit(1);
});

import { PERMISSIONS, ROLE_TEMPLATES, sectionOf } from './permissions';

/**
 * Renders docs/RBAC_PERMISSION_MATRIX.md from the catalogue and templates in permissions.ts.
 * `npm run docs:rbac` writes the file; tests/unit/rbac-doc.test.ts fails when the committed file is stale.
 * Never edit the generated part of the doc by hand.
 */
const ABBR: Record<string, string> = {
  super_admin: 'SA',
  state_admin: 'ADM',
  state_verifier: 'VER',
  state_approver: 'APP',
  auditor: 'AUD',
  district_officer: 'DIST',
  center_incharge: 'INCH',
  center_worker: 'WRK',
};

const SECTION_TITLE: Record<string, string> = {
  dashboard: 'Dashboard',
  beneficiary: 'Beneficiaries',
  application: 'Pension applications',
  consent: 'Consent documents',
  verification: 'Verification queue',
  approval: 'Approval queue',
  ppo: 'PPO',
  payment: 'Payments',
  import: 'Imports',
  report: 'Reports and exports',
  master: 'Masters and settings',
  user: 'Users',
  role: 'Roles',
  audit: 'Audit',
  system: 'System',
};

export const renderRbacMatrix = (): string => {
  const out: string[] = [];
  out.push('# RBAC permission matrix');
  out.push('');
  out.push('<!-- GENERATED by `npm run docs:rbac` in services/pension-auth-service from src/domain/permissions.ts. Do not edit by hand: change the code, then regenerate. -->');
  out.push('');
  out.push('Permission codes have the shape `pension:<section>.<resource>.<action>`. In code they are referenced ONLY as `P.<NAME>` (lib/permission-codes.ts, rule R-RBAC-1).');
  out.push('');
  out.push('## 1. Roles');
  out.push('');
  out.push('| Abbr | Role code | Name | Hindi | Scope | MFA | Permissions |');
  out.push('|---|---|---|---|---|---|---|');
  for (const t of ROLE_TEMPLATES) {
    out.push(`| ${ABBR[t.code]} | \`${t.code}\` | ${t.en} | ${t.hi} | ${t.scope} | ${t.mfaRequired ? 'yes' : 'no'} | ${new Set(t.permissions).size} |`);
  }
  out.push('');
  out.push('Scope: STATE sees every District and Center; DISTRICT only its district; CENTER only its Center (lib/scope.ts).');
  out.push('');
  out.push('## 2. Permissions by section');
  out.push('');
  out.push('Legend: ✓ = the role template holds it. `scopes` = role levels allowed to hold it at all. 🔒 = sensitive (unmasked data or full export). ⛔ = non-delegable (only a Super Admin can grant a role holding it).');
  const sections = [...new Set(PERMISSIONS.map((p) => sectionOf(p.code)))];
  for (const s of sections) {
    out.push('');
    out.push(`### ${SECTION_TITLE[s] ?? s}`);
    out.push('');
    out.push(`| Code | Meaning | scopes | ${ROLE_TEMPLATES.map((t) => ABBR[t.code]).join(' | ')} |`);
    out.push(`|---|---|---|${ROLE_TEMPLATES.map(() => '---').join('|')}|`);
    for (const p of PERMISSIONS.filter((x) => sectionOf(x.code) === s)) {
      const flags = `${p.sensitive ? ' 🔒' : ''}${p.delegable ? '' : ' ⛔'}`;
      const cells = ROLE_TEMPLATES.map((t) => (t.permissions.includes(p.code) ? '✓' : ''));
      out.push(`| \`${p.code}\`${flags} | ${p.en} | ${p.scopes.join(', ')} | ${cells.join(' | ')} |`);
    }
  }
  out.push('');
  out.push(`Total: ${PERMISSIONS.length} permissions, ${ROLE_TEMPLATES.length} roles.`);
  out.push('');
  return out.join('\n');
};

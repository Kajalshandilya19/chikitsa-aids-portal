"use client";

import { useTranslations } from "next-intl";

import { useMemo, useState } from "react";
import { IconCircleCheckFilled as Check, IconSelector as ChevronsUpDown, IconRefresh as Loader2 } from "@tabler/icons-react";

import { Button } from "@/components/ui/button";
import {
  Command,
  CommandGroup,
  CommandInput,
  CommandItem,
  CommandList,
} from "@/components/ui/command";
import { Popover, PopoverContent, PopoverTrigger } from "@/components/ui/popover";
import { Skeleton } from "@/components/ui/skeleton";
import { cn } from "@/lib/utils";

/**
 * The one searchable filter dropdown this app uses.
 *
 * It began as a local component inside the analytics command shell and was reimplemented, a
 * little differently, for the report filter panel, two controls that pick one value out of a
 * long list, disagreeing about what a set filter looks like, what the empty row says, and how
 * a list too long to render is handled. This is the shell's version, extracted whole; the
 * report panel now renders the same control the filter bar does.
 *
 * It answers to two kinds of list, because the two callers genuinely have different ones:
 *
 *   CLIENT (default), the whole list is in hand (33 districts, the facilities `/meta`
 *     returns). Matching runs here over the raw array and only a bounded slice is mounted.
 *     cmdk's own filtering is off either way: it scores by MOUNTING every item, so an
 *     unfiltered list of thousands built thousands of DOM nodes on open and rescored them on
 *     every keystroke.
 *
 *   SERVER (`onSearchChange` given), the list is a page of matches for the current query
 *     and this component must not filter it again. Re-filtering a server's answer hides rows
 *     it considered matches, which is how a picker ends up claiming a facility does not exist.
 *
 * And to two kinds of ANSWER. Pass `multiple` and it selects a set rather than a value: the
 * ticks accumulate, the popover stays open, and the trigger reads "Dengue +2". The filters
 * that name a thing the reader may legitimately want several of, diagnoses, districts,
 * facilities, departments, facility tiers, use that mode; the ones where two values
 * describe no real row (an age band, a gender) stay single.
 *
 * Not in `components/ui/`: that directory is generated by the shadcn CLI and hand-authored
 * files there get overwritten. This composes those primitives rather than joining them.
 */

/** The value meaning "no filter". Shared so callers agree on the sentinel. */
export const ANY_VALUE = "__any__";

/** Options mounted at once. Beyond this the reader is searching, not scrolling. */
const OPTION_RENDER_LIMIT = 100;

export interface FilterComboboxOption {
  value: string;
  label: string;
  /** A trailing note, a district beside a facility, a code beside an item. */
  hint?: string;
}

interface FilterComboboxBaseProps {
  /** Singular noun, used only in the search box: "Search facility…". */
  placeholder: string;
  /** Shown on the trigger when nothing is picked, and as the reset row. e.g. "All Facilities". */
  allLabel: string;
  options: FilterComboboxOption[];
  className?: string;
  /** Width of the dropdown. Defaults to the trigger's own width. */
  contentClassName?: string;
  /** Render a skeleton instead, the list has not arrived yet. */
  loading?: boolean;
  /** Offer the reset row. Off for a filter that must have a value. */
  allowAny?: boolean;
  /**
   * Server-side search. Given, the component stops filtering `options` itself and reports
   * every keystroke here instead; the caller is expected to return a fresh page.
   */
  onSearchChange?: (query: string) => void;
  /** Server mode: a request is in flight. */
  searching?: boolean;
  /**
   * The label for `value` when it is not in the loaded page.
   *
   * Server mode only, and it is why this prop exists at all: the chosen value can be absent
   * from the current page of matches, so the trigger cannot always find its own label. The
   * caller remembers what the reader picked. Without it a set filter reads as unset.
   */
  selectedLabel?: string;
  /** Empty-list text. */
  emptyLabel?: string;
}

/** One value at a time. `ANY_VALUE` (or the empty string) means the filter is not set. */
interface SingleSelectProps {
  multiple?: false;
  value: string;
  onChange: (value: string) => void;
}

/**
 * Several values at once, for a filter that reads as "any of these", the diagnoses a
 * clinician wants counted together, the four districts a review covers.
 *
 * The empty array is "not set", the same state `ANY_VALUE` names on the single-select side:
 * a filter set to NOTHING would mean an empty dashboard, which is never what clearing a
 * dropdown is asking for. Selecting does not close the popover here, picking a second value
 * is the whole point of the control, and a popover that shut after each one would make the
 * common case four round trips through the trigger.
 */
interface MultiSelectProps {
  multiple: true;
  value: string[];
  onChange: (value: string[]) => void;
}

export type FilterComboboxProps = FilterComboboxBaseProps & (SingleSelectProps | MultiSelectProps);

export function FilterCombobox(props: FilterComboboxProps) {
  const tw = useTranslations("widgets");
  const {
    placeholder,
    allLabel,
    options,
    className,
    contentClassName,
    loading,
    allowAny = true,
    onSearchChange,
    searching,
    selectedLabel,
    emptyLabel,
  } = props;

  const [open, setOpen] = useState(false);
  const [query, setQuery] = useState("");
  const serverSearched = Boolean(onSearchChange);

  // Both modes reduce to a list of chosen values, so everything below this line, the
  // trigger's label, the tick beside a row, the filled/unfilled styling, is written once.
  const selected = useMemo<string[]>(() => {
    if (props.multiple) return props.value;
    return props.value === ANY_VALUE || props.value === "" ? [] : [props.value];
  }, [props.multiple, props.value]);

  const matches = useMemo(() => {
    if (serverSearched) return options;
    const q = query.trim().toLowerCase();
    return q ? options.filter((o) => o.label.toLowerCase().includes(q)) : options;
  }, [options, query, serverSearched]);

  // Server mode already returns a page; slicing it again would hide matches it sent.
  const shown = serverSearched ? matches : matches.slice(0, OPTION_RENDER_LIMIT);
  const overflow = serverSearched ? 0 : matches.length - shown.length;

  if (loading) return <Skeleton className={cn("h-9", className)} />;

  const isSet = selected.length > 0;
  const labelOf = (value: string): string => options.find((o) => o.value === value)?.label ?? value;
  // One value shows its name; several show the first plus a count, because the trigger is a
  // fixed-width control in a single-line bar and three names truncate to three ellipses.
  const triggerLabel = !isSet
    ? allLabel
    : selected.length === 1
      ? (selectedLabel ?? labelOf(selected[0]!))
      : `${labelOf(selected[0]!)} +${selected.length - 1}`;

  const clear = () => {
    if (props.multiple) props.onChange([]);
    else props.onChange(ANY_VALUE);
    setOpen(false);
  };

  const choose = (value: string) => {
    if (props.multiple) {
      props.onChange(selected.includes(value) ? selected.filter((v) => v !== value) : [...selected, value]);
      return;
    }
    props.onChange(value);
    setOpen(false);
  };

  const search = (next: string) => {
    setQuery(next);
    onSearchChange?.(next);
  };

  return (
    <Popover
      open={open}
      // Clearing on close, so reopening never shows a list still narrowed by the last visit.
      onOpenChange={(next) => {
        setOpen(next);
        if (!next) search("");
      }}
    >
      <PopoverTrigger asChild>
        <Button
          variant="outline"
          role="combobox"
          aria-expanded={open}
          className={cn(
            // `min-w-0` so the label can truncate rather than set the control's width: inside a
            // dialog (a CSS grid, items min-width:auto) a long facility name otherwise widened
            // the button, the button widened the column, and the column pushed the dialog's own
            // footer outside its background.
            "h-9 min-w-0 shrink-0 justify-between gap-1.5 font-normal",
            // A set filter is shown by FILLING the control, not by tinting its outline: a
            // ringed control in a row of outline buttons reads as the one with a problem.
            isSet && "border-transparent bg-primary/10 text-primary hover:bg-primary/15 hover:text-primary",
            className,
          )}
        >
          <span className={cn("truncate", !isSet && "text-muted-foreground")}>{triggerLabel}</span>
          <ChevronsUpDown className="size-3.5 shrink-0 opacity-50" />
        </Button>
      </PopoverTrigger>
      {/*
        Focus lands in the search box on open, Radix's default, and NOT prevented.

        This carried `onOpenAutoFocus={e => serverSearched && e.preventDefault()}`, inherited
        from the report picker this component replaced. Preventing it leaves focus on the
        TRIGGER, which is outside the popover content: cmdk listens for keys on its own root, so
        every keystroke went nowhere and the search box simply did not respond. The filter bar
        never had the line, which is why searching worked there and not on a report.
      */}
      <PopoverContent className={cn("w-[240px] p-0", contentClassName)} align="start">
        {/* `shouldFilter={false}` in both modes, see the note at the top of this file. */}
        <Command shouldFilter={false}>
          <CommandInput
            value={query}
            onValueChange={search}
            placeholder={tw("searchIn", { what: placeholder })}
            className="h-9"
          />
          <CommandList>
            {searching && (
              <div className="text-muted-foreground flex items-center gap-2 px-3 py-2 text-xs">
                <Loader2 className="size-3.5 animate-spin" /> {tw("loading")}
              </div>
            )}
            {!searching && shown.length === 0 && (
              <p className="text-muted-foreground px-3 py-4 text-center text-xs">{emptyLabel ?? tw("noMatch")}</p>
            )}
            <CommandGroup>
              {allowAny && (
                <CommandItem value={allLabel} onSelect={clear}>
                  <span className="truncate">{allLabel}</span>
                  <Check className={cn("ml-auto size-4 shrink-0 self-center text-primary", !isSet ? "opacity-100" : "opacity-0")} />
                </CommandItem>
              )}
              {shown.map((o) => (
                <CommandItem
                  key={o.value}
                  // Server mode keys selection on the VALUE: two facilities can share a name,
                  // and cmdk treats the item value as its identity.
                  value={serverSearched ? o.value : o.label}
                  onSelect={() => choose(o.value)}
                >
                  <span className="min-w-0 flex-1 truncate">{o.label}</span>
                  {o.hint && <span className="text-muted-foreground shrink-0 text-[11px]">{o.hint}</span>}
                  <Check
                    className={cn("ml-auto size-4 shrink-0 self-center text-primary", selected.includes(o.value) ? "opacity-100" : "opacity-0")}
                  />
                </CommandItem>
              ))}
            </CommandGroup>
            {overflow > 0 && (
              <p className="text-muted-foreground border-t px-3 py-2 text-[11px]">
                {tw("moreKeepTyping", { count: overflow })}
              </p>
            )}
          </CommandList>
        </Command>
      </PopoverContent>
    </Popover>
  );
}
